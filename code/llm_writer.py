"""Генерация статьи через Claude (ProxyAPI).

Промпт нацелен на «человеческую» интонацию: личное, неровное по ритму,
с примерами и ошибками. Возвращает структуру {title, body, lead}.
"""
from __future__ import annotations

import json
import logging
import re
import textwrap

import requests

import config

log = logging.getLogger(__name__)


SYSTEM_PROMPT = textwrap.dedent("""\
    Ты ведёшь личный блог о дизайне интерьера на платформе Дзен.
    Автор — МУЖЧИНА 34 лет. Пиши строго от мужского лица:
    «я делал», «я думал», «я выбирал», «уверен», «согласен», «купил».
    Никогда не используй женские формы глаголов и причастий
    («делала», «думала», «уверена», «согласна», «купила»).

    Тон — тёплый, разговорный, как будто пишешь другу, который
    тоже разбирается в теме. Не корпоративный, не сухой.

    Главные правила:
    - Пиши от первого лица мужского рода. «Я», «мы», «у нас дома».
    - Один-два личных примера или истории в каждой статье. Можно вспомнить
      клиента, друга, маму, прошлый ремонт.
    - Не используй маркеры «топ-10», «вы узнаете», «прежде всего», «итак»,
      «в современном мире», «безусловно». Это машинные штампы.
    - Чередуй длинные и короткие предложения. Иногда — фрагмент. Так живее.
    - Один раз позволь себе ироничный комментарий или сомнение —
      «не уверена, что это всем подойдёт», «у меня такое спорное чувство».
    - Никогда не используй смайлики и эмодзи в тексте.
    - Не ставь H1 в тело — Дзен сам подставит заголовок из title.
      Внутри допускаются 2-3 подзаголовка (форматируй как «## Подзаголовок»).
    - Объём: 3500–5500 знаков с пробелами в body. Это 5–8 минут чтения.
    - Финал — без морали. Просто живая мысль или вопрос читателю.
    - **Каждый текст обязательно заканчивается отдельным абзацем строкой:
      «До новых идей.»** — без вариаций, ровно эта фраза, в конце body.
    - Конкретные цены/размеры/бренды — приветствуются, если естественны.
      Никогда не выдумывай конкретный бренд если он спорен — лучше «недорогая
      сетевая марка».

    Формат ответа — строго JSON, без префиксов и без ```:
    {"title": "<заголовок до 70 символов>",
     "lead": "<lead-абзац 1-2 предложения, чем зацепить>",
     "body": "<тело статьи в Markdown, без H1>"}
""")


def _user_prompt(title_hint: str, angle: str) -> str:
    angle_brief = {
        "personal_story": "Личная история. Расскажи, как будто было с тобой "
                          "или близким человеком. С деталями, ошибками, тем "
                          "что в итоге сработало.",
        "list": "Список из 5–7 пунктов, но не в шаблоне «совет 1, совет 2». "
                "Каждый пункт — короткая история или наблюдение. Между "
                "пунктами могут быть мостики.",
        "comparison": "Сравнение двух подходов / стилей / решений. "
                      "Без однозначного победителя — взвешенно, с твоим "
                      "субъективным предпочтением в финале.",
        "argument": "Текст-рассуждение. Возьми спорный вопрос, покрути его "
                    "с разных сторон, дойди до личного вывода.",
        "trend": "Про тренд. Покажи откуда он растёт и что в нём для жизни. "
                 "Без снобизма — что взять, что оставить.",
        "expert": "Чуть более экспертный текст, но всё равно от первого лица. "
                  "Раскрой нюанс, который дилетант может пропустить.",
    }.get(angle, "Свободно, как сама захочешь.")
    return textwrap.dedent(f"""\
        Заголовок-зацепка (черновой): «{title_hint}»

        Подход к подаче: {angle_brief}

        Сгенерируй полную статью под этот черновой заголовок.
        Ты можешь переформулировать его, чтобы он звучал по-человечески.
    """)


def write_article(title_hint: str, angle: str) -> dict:
    """Возвращает {'title': str, 'lead': str, 'body': str}."""
    payload = {
        "model": config.LLM_MODEL,
        "max_tokens": 4096,
        "system": SYSTEM_PROMPT,
        "messages": [
            {"role": "user", "content": _user_prompt(title_hint, angle)},
        ],
    }
    headers = {
        "x-api-key": config.PROXYAPI_KEY,
        "anthropic-version": "2023-06-01",
        "content-type": "application/json",
    }
    url = f"{config.PROXYAPI_ANTHROPIC_BASE}/v1/messages"

    log.info("LLM запрос: %s, hint=%r", config.LLM_MODEL, title_hint)
    r = requests.post(url, headers=headers, json=payload, timeout=180)
    r.raise_for_status()
    data = r.json()

    content = data.get("content", [])
    if not content or "text" not in content[0]:
        raise RuntimeError(f"Ответ Claude без текста: {data}")
    raw = content[0]["text"].strip()

    # Уберём ``` если завернул в код
    raw = re.sub(r"^```(?:json)?\s*|\s*```$", "", raw.strip(), flags=re.M)
    # Возьмём первый JSON-блок если есть лишнее
    if not raw.startswith("{"):
        m = re.search(r"\{[\s\S]+\}", raw)
        if m:
            raw = m.group(0)

    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError as exc:
        log.error("Не разобрал JSON: %r", raw[:300])
        raise RuntimeError(f"Claude вернул не-JSON: {exc}") from exc

    for key in ("title", "lead", "body"):
        if key not in parsed:
            raise RuntimeError(f"В ответе Claude нет ключа {key}")
    return {
        "title": parsed["title"].strip(),
        "lead": parsed["lead"].strip(),
        "body": parsed["body"].strip(),
    }
