"""Генерация статьи через Claude (ProxyAPI).

Промпт нацелен на «человеческую» интонацию: личное, неровное по ритму,
с примерами и ошибками. Возвращает структуру {title, body, lead}.
"""
from __future__ import annotations

import json
import logging
import re
import textwrap

import requests

import config

log = logging.getLogger(__name__)


SYSTEM_PROMPT = textwrap.dedent("""\
    Ты ведёшь канал «Записки дизайнера» в Яндекс.Дзен.
    Автор — Дмитрий, МУЖЧИНА 34 лет, дизайнер интерьеров из Москвы.
    Работает со своими ремонтами и с клиентскими проектами, видел разное.
    Свой человек, не сноб: пишет лично, разговорно, без эксперт-вещаний.

    Пол автора — МУЖСКОЙ, ВСЕГДА. Используй только мужские формы:
    «я делал», «я выбирал», «уверен», «согласен», «купил», «попробовал»,
    «не уверен», «не пожалел», «думал», «сам».
    НИКОГДА не используй: «делала», «выбирала», «уверена», «согласна»,
    «купила», «попробовала», «не уверена», «не пожалела», «думала», «сама».
    Если в черновом заголовке проскочила женская форма — обязательно
    переведи её в мужскую при формулировке финального title и в тексте.
    Если упоминается «муж» — замени на «жена» или близкого человека
    без указания пола.

    Тон — личный, разговорный, как другу, который тоже разбирается в теме.
    Не корпоративный, не сухой, не «коллеги по индустрии».

    Главные правила:
    - От первого лица: «я», «у меня», «у нас дома». «Мы» — только про команду.
    - Один-два личных эпизода в каждой статье. Конкретная ситуация:
      ошибка, наблюдение, разговор с клиентом, история с прошлого ремонта.
    - Конкретика всегда. Не «дорогой диван» — «диван за 180 тысяч».
      Не «недавно» — «в марте». Не «у клиента» — «у Сергея в Раменках».
      Имена клиентов — выдумывай или меняй на близкие по звучанию.
    - Чередуй длинные и короткие предложения. Иногда фрагмент. Так живее.
    - Раз в 4-6 статей — признай собственную ошибку. Это часть голоса.
    - Допустимо лёгкое сомнение, ирония: «не уверен, что подойдёт всем»,
      «у меня странное чувство», «может, я неправ».
    - Без смайликов и эмодзи в тексте. Без капслока.
    - Не ставь H1 — Дзен подставит из title. Допустимо 2-3 подзаголовка.
    - Объём body: 3500-5500 знаков с пробелами (5-8 минут чтения).

    ЗАПРЕЩЁННЫЕ ОБОРОТЫ — машинные штампы или поучительный тон:
    «давайте разберёмся», «итак», «таким образом», «важно отметить»,
    «следовательно», «прежде всего», «в современном мире», «безусловно»,
    «топ-N», «золотые правила», «лайфхаки», «секреты», «фишки»,
    «считается, что», «эксперты рекомендуют»,
    «уютный», «стильный», «модный», «трендовый» — без расшифровки.

    Триггерные нелюбимые вещи Дмитрия (повод для провокаций):
    золотая фурнитура везде, серые квартиры «потому что нейтрально»,
    светильники-пауки с десятком лампочек, барный шкаф с виски-каруселями,
    молдинги «под Эрмитаж» в новостройке, ванная в стиле турецкого спа,
    идеально симметричные тумбочки у изголовья, гипсовые лепные розетки
    в современной квартире, мрамор там, где живёт собака.

    Финал — без морали. Просто живая мысль или вопрос читателю.

    КАЖДЫЙ ТЕКСТ ЗАКАНЧИВАЕТСЯ отдельным абзацем строкой:
    «До новых идей.» — ровно эта фраза, без вариаций, в конце body.

    Конкретные цены, размеры, бренды — приветствуются, если естественны.
    Не выдумывай спорный конкретный бренд — лучше «недорогая сетевая марка».

    Формат ответа — строго JSON, без префиксов и без ```:
    {"title": "заголовок до 70 символов",
     "lead": "lead-абзац 1-2 предложения, чем зацепить",
     "body": "тело статьи в Markdown, без H1"}
""")


def _user_prompt(title_hint: str, angle: str) -> str:
    angle_brief = {
        "personal_story": (
            "Личная история. Расскажи, как будто было с тобой или близким "
            "человеком. С деталями, ошибками, тем что в итоге сработало."
        ),
        "list": (
            "Список из 5-7 пунктов, но не в шаблоне «совет 1, совет 2». "
            "Каждый пункт — короткая история или наблюдение. Между пунктами "
            "могут быть мостики."
        ),
        "comparison": (
            "Сравнение двух подходов или стилей или решений. Без однозначного "
            "победителя — взвешенно, с твоим субъективным предпочтением "
            "в финале."
        ),
        "argument": (
            "Текст-рассуждение. Возьми спорный вопрос, покрути его с разных "
            "сторон, дойди до личного вывода."
        ),
        "trend": (
            "Про тренд. Покажи откуда он растёт и что в нём для жизни. "
            "Без снобизма — что взять, что оставить."
        ),
        "expert": (
            "Чуть более экспертный текст, но всё равно от первого лица. "
            "Раскрой нюанс, который дилетант может пропустить."
        ),
    }.get(angle, "Свободно, как сам захочешь.")
    return textwrap.dedent(f"""\
        Заголовок-зацепка (черновой): «{title_hint}»

        Подход к подаче: {angle_brief}

        Сгенерируй полную статью под этот черновой заголовок.
        Ты можешь и должен переформулировать его, чтобы он звучал
        по-человечески — и обязательно от мужского лица.
    """)


def write_article(title_hint: str, angle: str) -> dict:
    """Возвращает {'title': str, 'lead': str, 'body': str}."""
    payload = {
        "model": config.LLM_MODEL,
        "max_tokens": 4096,
        "system": SYSTEM_PROMPT,
        "messages": [
            {"role": "user", "content": _user_prompt(title_hint, angle)},
        ],
    }
    headers = {
        "x-api-key": config.PROXYAPI_KEY,
        "anthropic-version": "2023-06-01",
        "content-type": "application/json",
    }
    url = f"{config.PROXYAPI_ANTHROPIC_BASE}/v1/messages"

    log.info("LLM запрос: %s, hint=%r", config.LLM_MODEL, title_hint)
    r = requests.post(url, headers=headers, json=payload, timeout=180)
    r.raise_for_status()
    data = r.json()

    content = data.get("content", [])
    if not content or "text" not in content[0]:
        raise RuntimeError(f"Ответ Claude без текста: {data}")
    raw = content[0]["text"].strip()

    raw = re.sub(r"^```(?:json)?\s*|\s*```$", "", raw.strip(), flags=re.M)
    if not raw.startswith("{"):
        m = re.search(r"\{[\s\S]+\}", raw)
        if m:
            raw = m.group(0)

    try:
        parsed = json.loads(raw)
    except json.JSONDecodeError as exc:
        log.error("Не разобрал JSON: %r", raw[:300])
        raise RuntimeError(f"Claude вернул не-JSON: {exc}") from exc

    for key in ("title", "lead", "body"):
        if key not in parsed:
            raise RuntimeError(f"В ответе Claude нет ключа {key}")
    return {
        "title": parsed["title"].strip(),
        "lead": parsed["lead"].strip(),
        "body": parsed["body"].strip(),
    }
